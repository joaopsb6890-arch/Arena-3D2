// Catmull-Rom escalar
function cr(p0, p1, p2, p3, t){
  const t2 = t * t, t3 = t2 * t;
  return 0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 + (-p0 + 3 * p1 - 3 * p2 + p3) * t3);
}
/** Avalia uma trilha [[t, v0, v1, ...], ...] no tempo t → array */
export function sampleTrack(keys, t, loop, dur, out){
  const n = keys.length, w = keys[0].length - 1;
  out = out || new Array(w);
  if(n === 1){ for(let k = 0; k < w; k++) out[k] = keys[0][k + 1]; return out; }
  if(loop) t = ((t % dur) + dur) % dur;
  if(t <= keys[0][0] && !loop){ for(let k = 0; k < w; k++) out[k] = keys[0][k + 1]; return out; }
  if(t >= keys[n - 1][0] && !loop){ for(let k = 0; k < w; k++) out[k] = keys[n - 1][k + 1]; return out; }
  let i = 0;
  while(i < n - 1 && keys[i + 1][0] <= t) i++;
  const a = keys[i], b = keys[(i + 1) % n];
  const tb = i + 1 < n ? b[0] : dur + keys[0][0];
  const u = Math.min(1, Math.max(0, (t - a[0]) / Math.max(1e-5, tb - a[0])));
  const p = loop ? keys[(i - 1 + n) % n] : keys[Math.max(0, i - 1)];
  const q = loop ? keys[(i + 2) % n] : keys[Math.min(n - 1, i + 2)];
  for(let k = 0; k < w; k++) out[k] = cr(p[k + 1], a[k + 1], b[k + 1], q[k + 1], u);
  return out;
}

